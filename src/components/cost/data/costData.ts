export interface FixedOverheadItem {
  id: number;
  costItem: string;
  totalCost: number;
  remark: string;
}

export interface DailyVariableOverheadItem {
  id: number;
  costItem: string;
  total: number;
  dailyValues: number[]; // 31 days (1..31)
}

export interface ProductPlItem {
  id: number;
  productName: string;
  salesAmount: number;
  salesRatio: number; // %
  indirectCostAllocated: number;
  logisticsRatio: number; // %
  logisticsCost: number;
  directMaterialUnit: number; // 단기총투입재료비
  productionQty: number;
  directMaterialCost: number;
  totalCost: number;
  salesProfit: number;
  profitRate: number; // %
  costRatio: number; // %
  salesQty: number;
  unitPrice: number; // 개당판매단가
  unitCost: number; // 단위원가
  unitProfit: number; // 개당손익
}

export interface CostGroupSummaryItem {
  id: number;
  groupName: string;
  costItem: string;
  costTotal: number;
  costToSalesRatio: number;
  groupSubtotal: number;
}

export interface MonthlyPlRowItem {
  id: number;
  costItem: string;
  costToSalesRatio: string;
  total: number;
  dailyValues: number[]; // 31 days
}

export interface RecipeCostRateItem {
  id: number;
  itemCode: string;
  itemType: string;
  category: string;
  itemName: string;
  spec: string;
  unit: string;
  packType: string;
  lineName: string; // 계명칭
  recipeCost: number; // 레시피원가
  deliveryPrice: number; // 납품단가
  diff: number; // 차이 = 납품단가 - 레시피원가
  costRate: number; // 원가율 = (레시피원가 / 납품단가) * 100
  remark: string;
}

